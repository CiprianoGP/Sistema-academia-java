    // carrega os JComboBox com os OBJETOS que vêm do banco.
    // O texto mostrado no combo é o toString() de cada classe.
    private void carregarCombos() {
        jCaluno.removeAllItems();
        for (Aluno a : new AlunoControle().listar()) {
            jCaluno.addItem(a);
        }
        jCplano.removeAllItems();
        for (Plano p : new PlanoControle().listar()) {
            jCplano.addItem(p);
        }
        jCmodalidade.removeAllItems();
        for (Modalidade mo : new ModalidadeControle().listar()) {
            jCmodalidade.addItem(mo);
        }
        jCinstrutor.removeAllItems();
        for (Instrutor i : new InstrutorControle().listar()) {
            jCinstrutor.addItem(i);
        }
    }

    // R - LISTAR: usa a consulta com INNER JOIN, então mostra os NOMES e não os códigos
    private void carregarTabela() {
        DefaultTableModel modelo = (DefaultTableModel) jTmatricula.getModel();
        modelo.setRowCount(0);
        ArrayList<Matricula> lista = controle.listar();
        for (int i = 0; i < lista.size(); i++) {
            Matricula m = lista.get(i);
            modelo.addRow(new Object[]{m.getCodigo(), m.getAluno().getNome(), m.getPlano().getDescricao(),
                m.getModalidade().getNome(), m.getInstrutor().getNome(), m.getDataInicio(),
                m.getDataVencimento(), String.format("%.2f", m.getValor()), m.getSituacao()});
        }
    }

    // monta o objeto Matricula com o que está na tela
    private Matricula lerCampos() {
        Matricula m = new Matricula();
        m.setCodigo(lerCodigo());
        // o JComboBox guarda o próprio objeto, então basta fazer o cast
        m.setAluno((Aluno) jCaluno.getSelectedItem());
        m.setPlano((Plano) jCplano.getSelectedItem());
        m.setModalidade((Modalidade) jCmodalidade.getSelectedItem());
        m.setInstrutor((Instrutor) jCinstrutor.getSelectedItem());
        m.setDataInicio(jTdataInicio.getText().trim());
        m.setSituacao(jCsituacao.getSelectedItem().toString());
        return m;
    }

    private void preencherCampos(Matricula m) {
        jTcodigo.setText(String.valueOf(m.getCodigo()));
        selecionarNoCombo(jCaluno, m.getAluno().getCodigo());
        selecionarNoCombo(jCplano, m.getPlano().getCodigo());
        selecionarNoCombo(jCmodalidade, m.getModalidade().getCodigo());
        selecionarNoCombo(jCinstrutor, m.getInstrutor().getCodigo());
        jTdataInicio.setText(m.getDataInicio());
        jTvencimento.setText(m.getDataVencimento());
        jTvalor.setText(String.format("%.2f", m.getValor()));
        jCsituacao.setSelectedItem(m.getSituacao());
    }

    // procura no combo o item cujo texto começa com "codigo - " (veja o toString das classes)
    private void selecionarNoCombo(JComboBox<Object> combo, int codigo) {
        for (int i = 0; i < combo.getItemCount(); i++) {
            if (combo.getItemAt(i).toString().startsWith(codigo + " - ")) {
                combo.setSelectedIndex(i);
                return;
            }
        }
    }

    private void limparCampos() {
        jTcodigo.setText("");
        jTdataInicio.setText(LocalDate.now().format(DateTimeFormatter.ofPattern("dd/MM/yyyy")));
        jTvencimento.setText("");
        jTvalor.setText("");
        jCsituacao.setSelectedIndex(0);
    }

    private int lerCodigo() {
        try {
            return Integer.parseInt(jTcodigo.getText().trim());
        } catch (NumberFormatException e) {
            return 0;
        }
    }

