    // R - LISTAR: busca tudo pelo controle e mostra na tabela
    private void carregarTabela() {
        DefaultTableModel modelo = (DefaultTableModel) jTmodalidade.getModel();
        modelo.setRowCount(0); // limpa a tabela antes de preencher
        ArrayList<Modalidade> lista = controle.listar();
        for (int i = 0; i < lista.size(); i++) {
            Modalidade m = lista.get(i);
            modelo.addRow(new Object[]{m.getCodigo(), m.getNome(), m.getDescricao()});
        }
    }

    // pega o que foi digitado na tela e coloca num objeto Modalidade
    private Modalidade lerCampos() {
        Modalidade m = new Modalidade();
        m.setCodigo(lerCodigo());
        m.setNome(jTnome.getText());
        m.setDescricao(jTdescricao.getText());
        return m;
    }

    // mostra os dados do objeto nos campos da tela
    private void preencherCampos(Modalidade m) {
        jTcodigo.setText(String.valueOf(m.getCodigo()));
        jTnome.setText(m.getNome());
        jTdescricao.setText(m.getDescricao());
    }

    private void limparCampos() {
        jTcodigo.setText("");
        jTnome.setText("");
        jTdescricao.setText("");
        jTnome.requestFocus();
    }

    // converte o texto do campo código para int (0 se estiver vazio)
    private int lerCodigo() {
        try {
            return Integer.parseInt(jTcodigo.getText().trim());
        } catch (NumberFormatException e) {
            return 0;
        }
    }

