    // R - LISTAR: busca tudo pelo controle e mostra na tabela
    private void carregarTabela() {
        DefaultTableModel modelo = (DefaultTableModel) jTplano.getModel();
        modelo.setRowCount(0); // limpa a tabela antes de preencher
        ArrayList<Plano> lista = controle.listar();
        for (int i = 0; i < lista.size(); i++) {
            Plano p = lista.get(i);
            modelo.addRow(new Object[]{p.getCodigo(), p.getDescricao(), p.getDuracaoMeses(), String.format("%.2f", p.getValor())});
        }
    }

    // pega o que foi digitado na tela e coloca num objeto Plano
    private Plano lerCampos() {
        Plano p = new Plano();
        p.setCodigo(lerCodigo());
        p.setDescricao(jTdescricao.getText());
        try {
            p.setDuracaoMeses(Integer.parseInt(jTduracao.getText().trim()));
        } catch (NumberFormatException e) {
            p.setDuracaoMeses(0); // o controle vai avisar que está inválido
        }
        try {
            p.setValor(Double.parseDouble(jTvalor.getText().trim().replace(",", ".")));
        } catch (NumberFormatException e) {
            p.setValor(0); // o controle vai avisar que está inválido
        }
        return p;
    }

    // mostra os dados do objeto nos campos da tela
    private void preencherCampos(Plano p) {
        jTcodigo.setText(String.valueOf(p.getCodigo()));
        jTdescricao.setText(p.getDescricao());
        jTduracao.setText(String.valueOf(p.getDuracaoMeses()));
        jTvalor.setText(String.format("%.2f", p.getValor()));
    }

    private void limparCampos() {
        jTcodigo.setText("");
        jTdescricao.setText("");
        jTduracao.setText("");
        jTvalor.setText("");
        jTdescricao.requestFocus();
    }

    // converte o texto do campo código para int (0 se estiver vazio)
    private int lerCodigo() {
        try {
            return Integer.parseInt(jTcodigo.getText().trim());
        } catch (NumberFormatException e) {
            return 0;
        }
    }

