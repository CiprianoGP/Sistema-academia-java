    private void jBpesquisarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBpesquisarActionPerformed
        // R - PESQUISAR pelo código
        Aluno a = controle.pesquisar(lerCodigo());
        if (a != null) {
            preencherCampos(a);
        }
    }//GEN-LAST:event_jBpesquisarActionPerformed

    private void jBsalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBsalvarActionPerformed
        // C - CADASTRAR
        if (lerCodigo() != 0) {
            JOptionPane.showMessageDialog(this, "Esse registro já está cadastrado. Use Alterar, ou clique em Limpar para cadastrar um novo.");
            return;
        }
        if (controle.salvar(lerCampos())) {
            limparCampos();
            carregarTabela();
        }
    }//GEN-LAST:event_jBsalvarActionPerformed

    private void jBalterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBalterarActionPerformed
        // U - ALTERAR
        if (controle.alterar(lerCampos())) {
            limparCampos();
            carregarTabela();
        }
    }//GEN-LAST:event_jBalterarActionPerformed

    private void jBexcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBexcluirActionPerformed
        // D - EXCLUIR
        int codigo = lerCodigo();
        if (codigo <= 0) {
            JOptionPane.showMessageDialog(this, "Pesquise ou selecione o aluno na tabela primeiro!");
            return;
        }
        int resposta = JOptionPane.showConfirmDialog(this, "Deseja realmente excluir o aluno de código " + codigo + "?",
                "Confirmar exclusão", JOptionPane.YES_NO_OPTION);
        if (resposta == JOptionPane.YES_OPTION) {
            if (controle.excluir(codigo)) {
                limparCampos();
                carregarTabela();
            }
        }
    }//GEN-LAST:event_jBexcluirActionPerformed

    private void jBlimparActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBlimparActionPerformed
        limparCampos();
    }//GEN-LAST:event_jBlimparActionPerformed

    private void jTalunoMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTalunoMouseClicked
        // ao clicar numa linha da tabela, carrega o registro nos campos
        int linha = jTaluno.getSelectedRow();
        if (linha >= 0) {
            int codigo = Integer.parseInt(jTaluno.getValueAt(linha, 0).toString());
            Aluno a = controle.pesquisar(codigo);
            if (a != null) {
                preencherCampos(a);
            }
        }
    }//GEN-LAST:event_jTalunoMouseClicked

