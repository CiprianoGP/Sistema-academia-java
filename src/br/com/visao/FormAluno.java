    // R - LISTAR: busca tudo pelo controle e mostra na tabela
    private void carregarTabela() {
        DefaultTableModel modelo = (DefaultTableModel) jTaluno.getModel();
        modelo.setRowCount(0); // limpa a tabela antes de preencher
        ArrayList<Aluno> lista = controle.listar();
        for (int i = 0; i < lista.size(); i++) {
            Aluno a = lista.get(i);
            modelo.addRow(new Object[]{a.getCodigo(), a.getNome(), a.getCpf(), a.getTelefone(), a.getEmail()});
        }
    }

    // pega o que foi digitado na tela e coloca num objeto Aluno
    private Aluno lerCampos() {
        Aluno a = new Aluno();
        a.setCodigo(lerCodigo());
        a.setNome(jTnome.getText());
        a.setCpf(jTcpf.getText());
        a.setTelefone(jTtelefone.getText());
        a.setEmail(jTemail.getText());
        return a;
    }

    // mostra os dados do objeto nos campos da tela
    private void preencherCampos(Aluno a) {
        jTcodigo.setText(String.valueOf(a.getCodigo()));
        jTnome.setText(a.getNome());
        jTcpf.setText(a.getCpf());
        jTtelefone.setText(a.getTelefone());
        jTemail.setText(a.getEmail());
    }

    private void limparCampos() {
        jTcodigo.setText("");
        jTnome.setText("");
        jTcpf.setText("");
        jTtelefone.setText("");
        jTemail.setText("");
        jTnome.requestFocus();
    }

    // converte o texto do campo código para int (0 se estiver vazio)
    private int lerCodigo() {
        try {
            return Integer.parseInt(jTcodigo.getText().trim());
        } catch (NumberFormatException e) {
            return 0;
        }
    }

