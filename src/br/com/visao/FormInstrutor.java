    // R - LISTAR: busca tudo pelo controle e mostra na tabela
    private void carregarTabela() {
        DefaultTableModel modelo = (DefaultTableModel) jTinstrutor.getModel();
        modelo.setRowCount(0); // limpa a tabela antes de preencher
        ArrayList<Instrutor> lista = controle.listar();
        for (int i = 0; i < lista.size(); i++) {
            Instrutor ins = lista.get(i);
            modelo.addRow(new Object[]{ins.getCodigo(), ins.getNome(), ins.getCpf(), ins.getTelefone(), ins.getCref()});
        }
    }

    // pega o que foi digitado na tela e coloca num objeto Instrutor
    private Instrutor lerCampos() {
        Instrutor ins = new Instrutor();
        ins.setCodigo(lerCodigo());
        ins.setNome(jTnome.getText());
        ins.setCpf(jTcpf.getText());
        ins.setTelefone(jTtelefone.getText());
        ins.setCref(jTcref.getText());
        return ins;
    }

    // mostra os dados do objeto nos campos da tela
    private void preencherCampos(Instrutor ins) {
        jTcodigo.setText(String.valueOf(ins.getCodigo()));
        jTnome.setText(ins.getNome());
        jTcpf.setText(ins.getCpf());
        jTtelefone.setText(ins.getTelefone());
        jTcref.setText(ins.getCref());
    }

    private void limparCampos() {
        jTcodigo.setText("");
        jTnome.setText("");
        jTcpf.setText("");
        jTtelefone.setText("");
        jTcref.setText("");
        jTnome.requestFocus();
    }

    // converte o texto do campo código para int (0 se estiver vazio)
    private int lerCodigo() {
        try {
            return Integer.parseInt(jTcodigo.getText().trim());
        } catch (NumberFormatException e) {
            return 0;
        }
    }

