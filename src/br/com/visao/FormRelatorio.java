    // RELATÓRIO da rotina principal: matrículas por período e situação
    private void gerarRelatorio() {
        ArrayList<Matricula> lista = controle.relatorio(jTdataInicial.getText().trim(),
                jTdataFinal.getText().trim(), jCsituacao.getSelectedItem().toString());
        DefaultTableModel modelo = (DefaultTableModel) jTrelatorio.getModel();
        modelo.setRowCount(0);
        for (int i = 0; i < lista.size(); i++) {
            Matricula m = lista.get(i);
            modelo.addRow(new Object[]{m.getCodigo(), m.getAluno().getNome(), m.getPlano().getDescricao(),
                m.getModalidade().getNome(), m.getInstrutor().getNome(), m.getDataInicio(),
                m.getDataVencimento(), String.format("%.2f", m.getValor()), m.getSituacao()});
        }
        jLtotal.setText("Total de matrículas: " + lista.size());
        jLvalorTotal.setText("Valor total: R$ " + String.format("%.2f", controle.calcularTotal(lista)));
    }

